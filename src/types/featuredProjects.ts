/**
 * "Featured Projects" section configuration.
 *
 * Stored in a single Firestore doc (`siteContent/featured_projects_settings`)
 * so the public section can pick it up in real time and the admin form can
 * edit it without a rebuild.
 */

export interface FeaturedProjectsSettings {
  /** Tech tags shown on a card before the "+N" chip. */
  tagsShown: number;
  /** Description lines shown on a card. */
  descriptionLines: number;
  /** Render the "Visit Site" button when a project has a landing page. */
  showVisitSite: boolean;
  /** Desktop columns of the cards grid (mobile stays 1). */
  cardsPerRow: 1 | 2 | 3 | 4;
  sectionTitle: string;
  sectionSubtitle: string;
}

export const FEATURED_PROJECTS_COLLECTION = "siteContent";
export const FEATURED_PROJECTS_DOC_ID = "featured_projects_settings";
export const FEATURED_PROJECTS_DOC_PATH = `${FEATURED_PROJECTS_COLLECTION}/${FEATURED_PROJECTS_DOC_ID}`;

export const FEATURED_PROJECTS_DEFAULTS: FeaturedProjectsSettings = {
  tagsShown: 8,
  descriptionLines: 5,
  showVisitSite: true,
  cardsPerRow: 3,
  sectionTitle: "Featured Projects",
  sectionSubtitle:
    "Explore our production-grade software platforms, cloud architectures, and mobile systems.",
};

export const FEATURED_PROJECTS_LIMITS = {
  tagsShown: { min: 1, max: 20 },
  descriptionLines: { min: 2, max: 8 },
  cardsPerRow: { min: 1, max: 4 },
  titleMaxLength: 120,
  subtitleMaxLength: 300,
} as const;

/** Static Tailwind classes — dynamic class names are not generated by the JIT. */
export const FEATURED_GRID_CLASSES: Record<1 | 2 | 3 | 4, string> = {
  1: "grid-cols-1",
  2: "grid-cols-1 sm:grid-cols-2",
  3: "grid-cols-1 sm:grid-cols-2 lg:grid-cols-3",
  4: "grid-cols-1 sm:grid-cols-2 lg:grid-cols-4",
};

const intInRange = (
  value: unknown,
  range: { min: number; max: number }
): number | null => {
  const num =
    typeof value === "number"
      ? value
      : typeof value === "string" && value.trim() !== ""
      ? Number(value)
      : NaN;
  if (!Number.isInteger(num) || num < range.min || num > range.max) return null;
  return num;
};

const isPlainObject = (v: unknown): v is Record<string, unknown> =>
  typeof v === "object" && v !== null && !Array.isArray(v);

export interface SettingsValidationResult {
  ok: boolean;
  settings: FeaturedProjectsSettings;
  errors: string[];
}

/**
 * Strict server-side validation for the settings API. Unknown keys are dropped,
 * missing keys fall back to defaults, invalid values are reported as errors.
 */
export function validateFeaturedProjectsSettings(
  input: unknown
): SettingsValidationResult {
  const errors: string[] = [];
  const raw = isPlainObject(input) ? input : {};
  const settings: FeaturedProjectsSettings = { ...FEATURED_PROJECTS_DEFAULTS };

  const numericFields: (keyof typeof FEATURED_PROJECTS_LIMITS)[] = [
    "tagsShown",
    "descriptionLines",
    "cardsPerRow",
  ];

  for (const field of numericFields) {
    const key = field as "tagsShown" | "descriptionLines" | "cardsPerRow";
    if (!(key in raw) || raw[key] === undefined || raw[key] === null) continue;
    const limits = FEATURED_PROJECTS_LIMITS[key] as { min: number; max: number };
    const parsed = intInRange(raw[key], limits);
    if (parsed === null) {
      errors.push(
        `${key} must be an integer between ${limits.min} and ${limits.max}`
      );
      continue;
    }
    if (key === "cardsPerRow") {
      settings.cardsPerRow = parsed as 1 | 2 | 3 | 4;
    } else {
      settings[key] = parsed;
    }
  }

  if ("showVisitSite" in raw && raw.showVisitSite !== undefined && raw.showVisitSite !== null) {
    if (typeof raw.showVisitSite !== "boolean") {
      errors.push("showVisitSite must be a boolean");
    } else {
      settings.showVisitSite = raw.showVisitSite;
    }
  }

  if ("sectionTitle" in raw && raw.sectionTitle !== undefined && raw.sectionTitle !== null) {
    if (typeof raw.sectionTitle !== "string" || !raw.sectionTitle.trim()) {
      errors.push("sectionTitle must be a non-empty string");
    } else if (raw.sectionTitle.length > FEATURED_PROJECTS_LIMITS.titleMaxLength) {
      errors.push(
        `sectionTitle must be at most ${FEATURED_PROJECTS_LIMITS.titleMaxLength} characters`
      );
    } else {
      settings.sectionTitle = raw.sectionTitle.trim();
    }
  }

  if ("sectionSubtitle" in raw && raw.sectionSubtitle !== undefined && raw.sectionSubtitle !== null) {
    if (typeof raw.sectionSubtitle !== "string") {
      errors.push("sectionSubtitle must be a string");
    } else if (raw.sectionSubtitle.length > FEATURED_PROJECTS_LIMITS.subtitleMaxLength) {
      errors.push(
        `sectionSubtitle must be at most ${FEATURED_PROJECTS_LIMITS.subtitleMaxLength} characters`
      );
    } else {
      settings.sectionSubtitle = raw.sectionSubtitle.trim();
    }
  }

  return { ok: errors.length === 0, settings, errors };
}

/** Lenient read used by the public UI so a corrupted doc never breaks a page. */
export function normalizeFeaturedProjectsSettings(
  input: unknown
): FeaturedProjectsSettings {
  const raw = isPlainObject(input) ? input : {};
  const clamp = (value: unknown, min: number, max: number, fallback: number) => {
    const num = typeof value === "number" ? value : Number(value);
    if (!Number.isFinite(num)) return fallback;
    return Math.min(max, Math.max(min, Math.round(num)));
  };
  const title =
    typeof raw.sectionTitle === "string" && raw.sectionTitle.trim()
      ? raw.sectionTitle.trim()
      : FEATURED_PROJECTS_DEFAULTS.sectionTitle;
  const subtitle =
    typeof raw.sectionSubtitle === "string"
      ? raw.sectionSubtitle.trim()
      : FEATURED_PROJECTS_DEFAULTS.sectionSubtitle;
  return {
    tagsShown: clamp(
      raw.tagsShown,
      FEATURED_PROJECTS_LIMITS.tagsShown.min,
      FEATURED_PROJECTS_LIMITS.tagsShown.max,
      FEATURED_PROJECTS_DEFAULTS.tagsShown
    ),
    descriptionLines: clamp(
      raw.descriptionLines,
      FEATURED_PROJECTS_LIMITS.descriptionLines.min,
      FEATURED_PROJECTS_LIMITS.descriptionLines.max,
      FEATURED_PROJECTS_DEFAULTS.descriptionLines
    ),
    showVisitSite:
      typeof raw.showVisitSite === "boolean"
        ? raw.showVisitSite
        : FEATURED_PROJECTS_DEFAULTS.showVisitSite,
    cardsPerRow: clamp(
      raw.cardsPerRow,
      FEATURED_PROJECTS_LIMITS.cardsPerRow.min,
      FEATURED_PROJECTS_LIMITS.cardsPerRow.max,
      FEATURED_PROJECTS_DEFAULTS.cardsPerRow
    ) as FeaturedProjectsSettings["cardsPerRow"],
    sectionTitle: title.slice(0, FEATURED_PROJECTS_LIMITS.titleMaxLength),
    sectionSubtitle: subtitle.slice(0, FEATURED_PROJECTS_LIMITS.subtitleMaxLength),
  };
}

/** Inline clamp style because Tailwind cannot generate `line-clamp-${n}`. */
export function descriptionClampStyle(lines: number) {
  return {
    display: "-webkit-box",
    WebkitBoxOrient: "vertical" as const,
    WebkitLineClamp: lines,
    overflow: "hidden",
  };
}
